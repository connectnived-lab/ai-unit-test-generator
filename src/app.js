// UI wiring only. Generation lives in src/core.
import { initSettingsPanel } from './ui/settings-panel.js';
import { $, setStatus, setBusy, downloadText } from './ui/common.js';
import { runGenerate } from './core/agent.js';
import { SAMPLE_MODULE } from './core/sample.js';

const settingsApi = initSettingsPanel();
const srcEl = $('src-input');
const nameEl = $('file-input');
const statusEl = $('status');
const runBtn = $('run-btn');
let lastText = '';
let lastName = 'module.test.js';

$('sample-btn').addEventListener('click', () => {
  srcEl.value = SAMPLE_MODULE;
  nameEl.value = 'math.js';
  setStatus(statusEl, 'Sample module loaded.', 'ok');
});

runBtn.addEventListener('click', async () => {
  setBusy(runBtn, true, 'Generating…');
  setStatus(statusEl, '');
  try {
    const moduleFile = nameEl.value.trim() || 'module.js';
    const result = await runGenerate({ src: srcEl.value, moduleFile, settings: settingsApi.get() });
    lastText = result.text;
    lastName = moduleFile.replace(/\.(m?js)$/, '') + '.test.js';
    $('summary').textContent = result.summary;
    $('output').textContent = result.text;
    $('result').hidden = false;
    $('download-btn').hidden = false;
    const count = result.tests ? result.tests.length : null;
    setStatus(statusEl, count === null ? 'Generated by the live model.' : `Generated ${count} tests.`, 'ok');
  } catch (err) {
    $('result').hidden = true;
    setStatus(statusEl, err.message, 'err');
  } finally {
    setBusy(runBtn, false);
  }
});

$('download-btn').addEventListener('click', () => downloadText(lastName, lastText, 'text/javascript'));
