// Builds the test file text and the summary a person reads before using it.
import { parseFunctions, callsInside } from './parse.js';
import { recordCases } from './golden.js';

export function planModule(src) {
  const all = parseFunctions(src);
  const names = all.map((f) => f.name);
  const exported = [];
  const skipped = [];
  for (const fn of all) {
    if (!fn.exported) {
      skipped.push({ name: fn.name, reason: 'not exported, so a test file cannot import it' });
    } else if (fn.isAsync) {
      skipped.push({ name: fn.name, reason: 'async, so it needs a hand-written test with real awaited input' });
    } else {
      exported.push(fn);
    }
  }
  return { all, names, exported, skipped };
}

export function generateTests({ src, moduleFile = 'module.js' }) {
  const plan = planModule(src);
  if (plan.exported.length === 0) {
    return {
      text: '',
      summary: { functions: plan.all.length, exported: 0, tests: 0, skipped: plan.skipped },
      tests: [],
    };
  }
  const importBase = moduleFile.replace(/\.(m?js)$/, '');
  const blocks = [];
  const tests = [];
  for (const fn of plan.exported) {
    const cases = recordCases(fn, src, plan.names);
    const integrationWith = callsInside(fn, plan.names);
    const label = integrationWith.length ? ` (integration: calls ${integrationWith.join(', ')})` : '';
    for (const c of cases) {
      const call = `${fn.name}(${c.argSrc})`;
      if (c.kind === 'returns') {
        const title = `${call} returns the recorded value${label}`;
        tests.push({ fn: fn.name, title, kind: 'returns' });
        blocks.push(`test(${JSON.stringify(title)}, () => {\n  assert.deepEqual(${call}, ${c.expected});\n});`);
      } else {
        const title = `${call} throws: ${c.message.slice(0, 60)}${label}`;
        tests.push({ fn: fn.name, title, kind: 'throws' });
        blocks.push(`test(${JSON.stringify(title)}, () => {\n  assert.throws(() => ${call});\n});`);
      }
    }
  }
  const header = [
    `// Generated by AI Unit Test Generator for ./${moduleFile}.`,
    '// Expected values were recorded from the current code. Review each one before you rely on it.',
    "import { test } from 'node:test';",
    "import assert from 'node:assert/strict';",
    `import { ${plan.exported.map((f) => f.name).join(', ')} } from './${importBase}.js';`,
    '',
  ].join('\n');
  const text = `${header}\n${blocks.join('\n\n')}\n`;
  return {
    text,
    summary: {
      functions: plan.all.length,
      exported: plan.exported.length,
      tests: tests.length,
      skipped: plan.skipped,
    },
    tests,
  };
}

export function summaryText(s) {
  const lines = [
    `${s.exported} of ${s.functions} functions are exported and covered; ${s.tests} tests generated.`,
  ];
  for (const k of s.skipped) lines.push(`Skipped ${k.name}: ${k.reason}.`);
  return lines.join('\n');
}
